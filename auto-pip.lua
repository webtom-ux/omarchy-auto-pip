  refresh_playing()
  if next(state.windows) then
    for _, win in ipairs(hl.get_windows()) do
      if state.windows[win.address] then
        remember_geometry(win)
      end
    end
  end
  reconcile()
end, { timeout = 500, type = "repeat" })

